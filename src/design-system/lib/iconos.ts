export const ICONO_PREDETERMINADO: LucideIcon = LayoutGrid;

function aKebab(nombre: string): string {
  return nombre
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Za-z])([0-9])/g, "$1-$2")
    .replace(/[\s_]+/g, "-")
    .toLowerCase();
}

/** Devuelve el componente de ícono para un nombre, o el ícono predeterminado. */
export function resolverIcono(nombre: string | null | undefined): LucideIcon {
  if (!nombre) return ICONO_PREDETERMINADO;
  return ICONOS[aKebab(nombre)] ?? ICONOS[nombre] ?? ICONO_PREDETERMINADO;
}

/** Nombres admitidos por `resolverIcono` (útil para validar el catálogo). */
export const NOMBRES_ICONOS: readonly string[] = Object.keys(ICONOS);
